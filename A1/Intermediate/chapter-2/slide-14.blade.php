@section('script')
    <script>
        document.addEventListener("DOMContentLoaded", () => {
            let currentAudio = null;

            function stopAll() {
                if (currentAudio) {
                    currentAudio.pause();
                    currentAudio.currentTime = 0;
                    currentAudio = null;
                }
                document.querySelectorAll('.vocab-item.speaking').forEach(el => el.classList.remove('speaking'));
            }

            function playItem(el) {
                const soundSrc = el.dataset.sound;
                if (!soundSrc) return;

                // If same is playing → stop
                if (currentAudio && currentAudio.src === soundSrc && !currentAudio.paused) {
                    stopAll();
                    return;
                }

                stopAll();

                const audio = new Audio(soundSrc);
                currentAudio = audio;
                el.classList.add('speaking');

                audio.play().catch(e => {
                    console.log("Audio play error:", e);
                    el.classList.remove('speaking');
                    if (currentAudio === audio) currentAudio = null;
                });

                audio.onended = () => {
                    el.classList.remove('speaking');
                    if (currentAudio === audio) currentAudio = null;
                };
            }

            document.querySelectorAll('.vocab-item').forEach(item => {
                item.addEventListener('click', () => playItem(item));

                // ✅ Keyboard support
                item.addEventListener('keydown', (e) => {
                    if (e.key === 'Enter' || e.key === ' ') {
                        e.preventDefault();
                        playItem(item);
                    }
                });
            });

            // --- Animation Logic ---
            if (!window.gsap) return;
            if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

            const title = document.querySelector(".anim-title");
            const panels = Array.from(document.querySelectorAll(".anim-panel"));
            const items  = Array.from(document.querySelectorAll(".anim-item"));

            gsap.killTweensOf([title, ...panels, ...items]);
            gsap.set([title, ...panels, ...items], { clearProps: "all" });

            gsap.timeline({ defaults: { ease: "power3.out" } })
                .from(title,  { opacity: 0, y: 10, duration: 0.65 }, 0.06)
                .from(panels, { opacity: 0, y: 8, duration: 0.5, stagger: 0.10 }, 0.22)
                .from(items,  { opacity: 0, y: 6, duration: 0.42, stagger: 0.012 }, 0.40);
        });
    </script>
@endsection
